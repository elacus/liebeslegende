def detect_language(locale: str | None) -> str:
    """Map the browser's locale to a supported language."""
    if locale:
        language_code = locale.replace("_", "-").split("-", maxsplit=1)[0].lower()
        if language_code in LANGUAGES:
            return language_code
    return "de"
